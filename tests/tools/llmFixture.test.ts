import { it } from 'vitest';
import type { DialogueProvider, World } from '../../src/types';
import { createWorld, tickWorld } from '../../src/world/world';
import { setNewsFeed } from '../../src/world/news';
import { buildLineRequest, type LlmLineRequest } from '../../src/social/llmProvider';
import { buildDiaryRequest, diaryFactsOf, onDiaryChange } from '../../src/social/diary';
import type { LlmDiaryRequest } from '../../src/social/diaryAi';

// Fixture for scripts/compare-models.mjs (#28): real LLM requests recorded from headless worlds.
// LLM_FIXTURE=1 npx vitest run tests/tools/llmFixture.test.ts → tests/fixtures/llm-requests.json

const MAPS = ['dom', 'kamienica', 'akademik', 'jezioro'];
const TICKS = 2 * 1440 + 120;
/** neutral stand-ins for real TV headlines (the live server fetches real ones) */
const HEADLINES = [
  { title: 'Synoptycy zapowiadają ochłodzenie i przelotne opady w całym kraju' },
  { title: 'Reprezentacja wygrywa mecz towarzyski 2:1' },
  { title: 'W miastach rusza sezon jarmarków jesiennych' },
];

type Picked = { id: string; why: string; request: LlmLineRequest };

function record(world: World, lines: LlmLineRequest[], diaries: LlmDiaryRequest[]): void {
  const inner = world.dialogue;
  const recorder: DialogueProvider = {
    name: inner.name,
    nextLine(ctx, rng) {
      lines.push(buildLineRequest(ctx));
      return inner.nextLine(ctx, rng);
    },
  };
  world.dialogue = recorder;
  onDiaryChange(world, (entry) => {
    const facts = diaryFactsOf(world, entry.agentId, entry.day);
    const agent = world.agents.find((a) => a.id === entry.agentId);
    if (facts && agent) diaries.push(buildDiaryRequest(facts, { name: agent.name, traits: { ...agent.traits }, mood: agent.mood }));
  });
}

/** a varied, stable selection: greetings, goodbyes, gossip, TV news, friends, foes, bad moods */
function pickLines(all: { map: string; r: LlmLineRequest }[]): Picked[] {
  const used = new Set<LlmLineRequest>();
  const out: Picked[] = [];
  const take = (why: string, n: number, pred: (r: LlmLineRequest) => boolean, order?: (r: LlmLineRequest) => number) => {
    const seenMaps = new Set<string>();
    const pool = order ? [...all].sort((a, b) => order(a.r) - order(b.r)) : all;
    for (const pass of [0, 1]) {
      for (const { map, r } of pool) {
        if (out.filter((p) => p.why === why).length >= n) return;
        if (used.has(r) || !pred(r) || (pass === 0 && seenMaps.has(map))) continue;
        used.add(r);
        seenMaps.add(map);
        out.push({ id: `line-${String(out.length + 1).padStart(2, '0')}`, why, request: r });
      }
    }
  };
  const mid = (r: LlmLineRequest) => r.turn > 0 && !r.isLast;
  take('first line (greeting)', 2, (r) => r.turn === 0);
  take('last line (goodbye)', 2, (r) => r.isLast && r.history.length >= 2);
  take('gossip available', 3, (r) => mid(r) && !!r.gossip?.length);
  take('shared memory', 1, (r) => mid(r) && !!r.gossip?.some((g) => g.shared));
  take('TV headlines', 2, (r) => mid(r) && !!r.news?.length);
  take('dislike', 2, (r) => mid(r) && r.relationship <= -20);
  // two short days rarely reach "best friends" or a terrible mood: take the extremes instead
  take('closest friends', 2, mid, (r) => -r.relationship);
  take('worst mood', 2, mid, (r) => r.mood);
  take('long history', 2, (r) => mid(r) && r.history.length >= 4);
  // residents are rarely miserable in two days: one real request with the mood pushed down
  const sad = out.find((p) => p.why === 'worst mood');
  if (sad) {
    const request = { ...sad.request, mood: 22, needs: 'głód, zmęczenie' };
    out.push({ id: `line-${String(out.length + 1).padStart(2, '0')}`, why: 'synthetic: bad mood (copy of a real request, mood 22)', request });
  }
  return out;
}

it.runIf(!!process.env.LLM_FIXTURE)('records the LLM request fixture', async () => {
  const { writeFileSync, mkdirSync } = await import('node:fs');
  const lines: { map: string; r: LlmLineRequest }[] = [];
  const diaries: { map: string; r: LlmDiaryRequest }[] = [];
  MAPS.forEach((mapId, i) => {
    const w = createWorld(28 + i, { mapId });
    // half of the worlds get "real" headlines too, like the live server
    if (i % 2 === 0) setNewsFeed(w, HEADLINES);
    const l: LlmLineRequest[] = [];
    const d: LlmDiaryRequest[] = [];
    record(w, l, d);
    for (let t = 0; t < TICKS; t++) tickWorld(w);
    lines.push(...l.map((r) => ({ map: mapId, r })));
    diaries.push(...d.map((r) => ({ map: mapId, r })));
  });
  const picked = pickLines(lines);
  // one diary per map: the one with the most facts from a full day (day 2+)
  const diaryPicks = MAPS.flatMap((map) => {
    const best = diaries.filter((d) => d.map === map && d.r.day >= 2).sort((a, b) => b.r.facts.length - a.r.facts.length)[0];
    return best ? [best.r] : [];
  });
  const fixture = {
    note: 'Generated by tests/tools/llmFixture.test.ts (#28); input for scripts/compare-models.mjs',
    lines: picked,
    diaries: diaryPicks.map((request, i) => ({ id: `diary-${i + 1}`, request })),
  };
  mkdirSync('tests/fixtures', { recursive: true });
  writeFileSync('tests/fixtures/llm-requests.json', JSON.stringify(fixture, null, 2) + '\n');
  console.log(`recorded ${lines.length} lines, ${diaries.length} diaries → picked ${picked.length} + ${diaryPicks.length}`);
}, 300_000);
